"""Writes documentation/file-inventory.md: every file in the project with its size.
Run from the butterskin folder:  python3 tools/inventory.py"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = f"{ROOT}/documentation/file-inventory.md"
rows, total = [], 0
for d, _, fs in sorted(os.walk(ROOT)):
    if "__pycache__" in d:
        continue
    for f in sorted(fs):
        p = os.path.join(d, f)
        if p == OUT:
            continue
        sz = os.path.getsize(p); total += sz
        rows.append((os.path.relpath(p, ROOT), sz))
groups = {}
for r, sz in rows:
    g = "/".join(r.split("/")[:2]) if r.count("/") >= 2 else r.split("/")[0] if "/" in r else "(root)"
    groups.setdefault(g, []).append((r, sz))
fmt = lambda n: f"{n / 1024:.1f} KB" if n < 1024 * 1024 else f"{n / 1024 / 1024:.2f} MB"
lines = ["# File Inventory", "", f"Generated by `tools/inventory.py`. **{len(rows) + 1} files, {fmt(total)}** (including this file).", "",
         "| Folder | Files | Size |", "|---|---|---|"]
for g, items in sorted(groups.items()):
    lines.append(f"| `{g}` | {len(items)} | {fmt(sum(s for _, s in items))} |")
lines += ["", "## All files", "", "| File | Size |", "|---|---|"]
lines += [f"| {r} | {fmt(sz)} |" for r, sz in rows]
lines.append("| documentation/file-inventory.md | (this file) |")
open(OUT, "w").write("\n".join(lines) + "\n")
print("inventory:", len(rows) + 1, "files")
