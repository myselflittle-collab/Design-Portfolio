"""Copies data/products.json into prototype/assets/data.js so the prototype works from file:// (no fetch needed).
Run from the butterskin folder:  python3 tools/build_data.py"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(f"{ROOT}/data/products.json"))
os.makedirs(f"{ROOT}/prototype/assets", exist_ok=True)
with open(f"{ROOT}/prototype/assets/data.js", "w") as f:
    f.write("/* Generated by tools/build_data.py from data/products.json. Do not edit by hand. Fictional concept content. */\n")
    f.write("window.BS_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
print("data.js written:", len(data["products"]), "products")
