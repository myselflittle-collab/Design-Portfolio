# ------------------------------------------------------------------ text to outlines
_fonts = {}


def _font(fname):
    if fname not in _fonts:
        tt = TTFont(f"{FONTS}/{fname}")
        tt.flavor = None
        buf = io.BytesIO(); tt.save(buf); data = buf.getvalue()
        face = hb.Face(hb.Blob(data)); font = hb.Font(face)
        tt2 = TTFont(io.BytesIO(data))
        _fonts[fname] = (font, tt2, tt2.getGlyphSet(), tt2["head"].unitsPerEm)
    return _fonts[fname]


SERIF = "playfair-display-latin-600-normal.woff2"
SANS_B = "dm-sans-latin-700-normal.woff2"
SANS_M = "dm-sans-latin-500-normal.woff2"


def text_path(text, fname, size, x=0, y=0, tracking=0.0):
    font, tt, gs, upem = _font(fname)
    buf = hb.Buffer(); buf.add_str(text); buf.guess_segment_properties()
    hb.shape(font, buf, {"kern": True, "liga": True})
    order = tt.getGlyphOrder(); s = size / upem; pen = SVGPathPen(gs); cx = 0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        gs[order[info.codepoint]].draw(TransformPen(pen, (s, 0, 0, -s, x + (cx + pos.x_offset) * s, y - pos.y_offset * s)))
        cx += pos.x_advance + tracking * upem
    return pen.getCommands(), (cx - tracking * upem) * s


def glyph_box(ch, fname, size):
    font, tt, gs, upem = _font(fname)
    g = tt.getBestCmap()[ord(ch)]; bp = BoundsPen(gs); gs[g].draw(bp)
    s = size / upem; x0, y0, x1, y1 = bp.bounds
    return x0 * s, y0 * s, x1 * s, y1 * s


# ------------------------------------------------------------------ mark & wordmark
OLIVE, CREAM, BUTTER, INK = hexval("olive.600"), hexval("paper.0"), hexval("butter.300"), hexval("ink.900")


def pat_path(cx, cy, size, rot=-8):
    """The 'pat': a soft square, three rounded corners and one tucked (bottom-left) corner."""
    h = size / 2; R = size * 0.42; r = size * 0.12
    x0, y0, x1, y1 = cx - h, cy - h, cx + h, cy + h
    d = (f"M{x0 + R:.2f} {y0:.2f} H{x1 - R:.2f} A{R:.2f} {R:.2f} 0 0 1 {x1:.2f} {y0 + R:.2f} V{y1 - R:.2f} "
         f"A{R:.2f} {R:.2f} 0 0 1 {x1 - R:.2f} {y1:.2f} H{x0 + r:.2f} A{r:.2f} {r:.2f} 0 0 1 {x0:.2f} {y1 - r:.2f} "
         f"V{y0 + R:.2f} A{R:.2f} {R:.2f} 0 0 1 {x0 + R:.2f} {y0:.2f} Z")
    return f'<path d="{d}" transform="rotate({rot} {cx} {cy})"'


def mark(cx, cy, size, bg=OLIVE, fg=CREAM):
    fs = size * 0.86
    x0, y0, x1, y1 = glyph_box("b", SERIF, fs)
    gx = cx - (x0 + x1) / 2; gy = cy + (y0 + y1) / 2 + size * 0.02
    d, _ = text_path("b", SERIF, fs, gx, gy)
    return f'{pat_path(cx, cy, size)} fill="{bg}"/><path d="{d}" fill="{fg}"/>'


def wordmark(x, baseline, size, color=INK):
    d, w = text_path("butterskin", SANS_B, size, x, baseline, tracking=-0.035)
    return f'<path d="{d}" fill="{color}"/>', w


def svg(vb, body, title, w=None, h=None):
    dim = f' width="{w}" height="{h}"' if w else ""
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}"{dim} role="img" aria-label="{title}"><title>{title}</title>{body}</svg>\n'


