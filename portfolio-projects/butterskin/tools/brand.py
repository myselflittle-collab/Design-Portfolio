# ------------------------------------------------------------------ packaging system
def label_text(lines, x, y, size, fname=SANS_M, color=INK, lh=1.2, center=True, maxw=None):
    out = []
    for i, ln in enumerate(lines):
        d, w = text_path(ln, fname, size, 0, 0)
        sc = min(1.0, maxw / w) if maxw else 1.0
        tx = x - w * sc / 2 if center else x
        out.append(f'<path d="{d}" fill="{color}" transform="translate({tx:.2f} {y + i * size * lh:.2f}) scale({sc:.3f})"/>')
    return "".join(out)


def split_name(name):
    words = name.split(); best = None
    for i in range(1, len(words)):
        a, b = " ".join(words[:i]), " ".join(words[i:])
        sc = max(len(a), len(b))
        if best is None or sc < best[0]: best = (sc, [a, b])
    return best[1] if best else [name]


def package(p, W=240, H=360):
    """One product illustration on a WxH canvas, standing on a soft shadow."""
    body_col = hexval(".".join(CATEGORY[p["category"]]))
    cap, shade = hexval("olive.800"), "rgba(38,41,31,.10)"
    fmt = p["format"]; cx = W / 2; base = H - 34
    parts = [f'<ellipse cx="{cx}" cy="{base + 6}" rx="{W * 0.32}" ry="10" fill="{shade}"/>']
    name = split_name(p["name"])
    if fmt == "tube":
        tw, th = 112, 240; top = base - th - 34
        parts.append(f'<path d="M{cx - tw / 2} {top} H{cx + tw / 2} L{cx + tw / 2 - 12} {top + th} H{cx - tw / 2 + 12} Z" fill="{body_col}" stroke="rgba(38,41,31,.22)" stroke-width="2"/>')
        box = (cx - tw / 2 + 4, top + 4, cx + tw / 2 - 16, top + th - 6)
        parts.append(f'<rect x="{cx - tw / 2 - 2}" y="{top - 6}" width="{tw + 4}" height="10" rx="3" fill="{hexval("paper.200")}"/>')
        parts.append(f'<rect x="{cx - 40}" y="{top + th}" width="80" height="34" rx="10" fill="{cap}"/>')
        ly = top + 56; lw = tw - 26
    elif fmt == "pump":
        bw, bh = 120, 196; top = base - bh
        parts.append(f'<rect x="{cx - bw / 2}" y="{top}" width="{bw}" height="{bh}" rx="26" fill="{body_col}" stroke="rgba(38,41,31,.22)" stroke-width="2"/>')
        box = (cx - bw / 2, top + 14, cx + bw / 2, base - 14)
        parts.append(f'<rect x="{cx - 22}" y="{top - 26}" width="44" height="28" rx="6" fill="{cap}"/>')
        parts.append(f'<rect x="{cx - 8}" y="{top - 64}" width="16" height="40" rx="4" fill="{cap}"/>')
        parts.append(f'<path d="M{cx - 30} {top - 70} H{cx + 40} a8 8 0 0 1 0 16 H{cx - 30} Z" fill="{cap}"/>')
        ly = top + 46; lw = bw - 28
    elif fmt == "dropper":
        bw, bh = 104, 150; top = base - bh
        parts.append(f'<rect x="{cx - bw / 2}" y="{top}" width="{bw}" height="{bh}" rx="22" fill="{body_col}" stroke="rgba(38,41,31,.22)" stroke-width="2"/>')
        box = (cx - bw / 2, top + 12, cx + bw / 2, base - 12)
        parts.append(f'<rect x="{cx - 28}" y="{top - 30}" width="56" height="34" rx="6" fill="{cap}"/>')
        parts.append(f'<path d="M{cx - 20} {top - 30} V{top - 62} a20 20 0 0 1 40 0 V{top - 30} Z" fill="{hexval("olive.600")}"/>')
        ly = top + 34; lw = bw - 22
    elif fmt == "jar":
        jw, jh = 170, 110; top = base - jh
        parts.append(f'<rect x="{cx - jw / 2}" y="{top}" width="{jw}" height="{jh}" rx="20" fill="{body_col}" stroke="rgba(38,41,31,.22)" stroke-width="2"/>')
        box = (cx - jw / 2, top + 10, cx + jw / 2, base - 10)
        parts.append(f'<rect x="{cx - jw / 2 - 6}" y="{top - 44}" width="{jw + 12}" height="50" rx="14" fill="{cap}"/>')
        ly = top + 18; lw = jw - 40
    else:  # bottle
        bw, bh = 108, 210; top = base - bh
        parts.append(f'<path d="M{cx - bw / 2} {top + 40} q0 -30 30 -36 h{bw - 60} q30 6 30 36 V{base - 18} a18 18 0 0 1 -18 18 H{cx - bw / 2 + 18} a18 18 0 0 1 -18 -18 Z" fill="{body_col}" stroke="rgba(38,41,31,.22)" stroke-width="2"/>')
        box = (cx - bw / 2, top + 24, cx + bw / 2, base - 14)
        parts.append(f'<rect x="{cx - 24}" y="{top - 40}" width="48" height="40" rx="8" fill="{cap}"/>')
        ly = top + 60; lw = bw - 24
    # soft highlight (left) and shade (right) so the pack reads on any background
    x0, y0, x1, y1 = box
    parts.append(f'<rect x="{x0 + 9}" y="{y0 + 6}" width="9" height="{y1 - y0 - 12}" rx="4.5" fill="#fff" opacity=".38"/>')
    parts.append(f'<rect x="{x1 - 16}" y="{y0 + 6}" width="8" height="{y1 - y0 - 12}" rx="4" fill="#26291F" opacity=".07"/>')
    # label: small pat + wordmark, product name, size
    lab_h = 74
    parts.append(f'<rect x="{cx - lw / 2}" y="{ly}" width="{lw}" height="{lab_h}" rx="8" fill="{hexval("paper.0")}"/>')
    parts.append(mark(cx - lw / 2 + 13, ly + 13, 13, OLIVE, CREAM))
    wm, ww = wordmark(0, 0, 10)
    parts.append(f'<g transform="translate({cx - lw / 2 + 24} {ly + 17})">{wm}</g>')
    parts.append(label_text(name, cx, ly + 36, 10.5, SANS_B, INK, 1.25, maxw=lw - 14))
    parts.append(label_text([f"{p['size']} · concept"], cx, ly + lab_h - 8, 8.5, SANS_M, hexval("ink.600")))
    return "".join(parts)


